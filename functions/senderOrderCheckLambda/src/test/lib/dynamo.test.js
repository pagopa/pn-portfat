const assert = require("assert");
const sinon = require("sinon");
const proxyquire = require("proxyquire").noCallThru();

describe("dynamo", () => {
    let mockSend;
    let mockDynamoDBClientInstance;
    let DynamoDBClient;
    let DynamoDBDocumentClient;
    let QueryCommand;
    let getCompletedRecordsByMonthSent;

    const loadModule = () => {
        const module = proxyquire("../../app/lib/dynamo", {
            "@aws-sdk/client-dynamodb": {
                DynamoDBClient
            },
            "@aws-sdk/lib-dynamodb": {
                DynamoDBDocumentClient,
                QueryCommand
            }
        });

        getCompletedRecordsByMonthSent =
            module.getCompletedRecordsByMonthSent;

        return module;
    };

    beforeEach(() => {
        delete process.env.PORTFAT_DOWNLOAD_TABLE_NAME;

        mockSend = sinon.stub();

        mockDynamoDBClientInstance = {
            clientType: "DynamoDBClient"
        };

        DynamoDBClient = sinon
            .stub()
            .returns(mockDynamoDBClientInstance);

        DynamoDBDocumentClient = {
            from: sinon.stub().returns({
                send: mockSend
            })
        };

        /*
         * We mock QueryCommand so that we can verify exactly
         * which payload is passed to it.
         */
        QueryCommand = sinon.spy(function QueryCommand(input) {
            this.input = input;
        });
    });

    afterEach(() => {
        delete process.env.PORTFAT_DOWNLOAD_TABLE_NAME;
        sinon.restore();
    });

    describe("client initialization", () => {
        it("should create a DynamoDBClient when the module is loaded", () => {
            loadModule();

            sinon.assert.calledOnce(DynamoDBClient);
            sinon.assert.calledWithExactly(DynamoDBClient);
        });

        it("should create DynamoDBDocumentClient from DynamoDBClient", () => {
            loadModule();

            sinon.assert.calledOnce(
                DynamoDBDocumentClient.from
            );

            sinon.assert.calledWithExactly(
                DynamoDBDocumentClient.from,
                mockDynamoDBClientInstance
            );
        });
    });

    describe("getCompletedRecordsByMonthSent", () => {
        it("should query COMPLETED records for the specified monthSent", async () => {
            const expectedItems = [
                {
                    id: "record-1",
                    status: "COMPLETED",
                    monthSent: "2026-10",
                    orderMonth: "2026-11"
                },
                {
                    id: "record-2",
                    status: "COMPLETED",
                    monthSent: "2026-10",
                    orderMonth: "2027-02"
                }
            ];

            mockSend.resolves({
                Items: expectedItems
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            const result =
                await getCompletedRecordsByMonthSent("2026-10");

            sinon.assert.calledOnce(QueryCommand);

            sinon.assert.calledWithExactly(
                QueryCommand,
                {
                    TableName: "pn-PortFatDownload",
                    IndexName: "statusMonthSent-index",

                    KeyConditionExpression:
                        "#status = :status AND #monthSent = :monthSent",

                    ExpressionAttributeNames: {
                        "#status": "status",
                        "#monthSent": "monthSent"
                    },

                    ExpressionAttributeValues: {
                        ":status": "COMPLETED",
                        ":monthSent": "2026-10"
                    }
                }
            );

            sinon.assert.calledOnce(mockSend);

            /*
             * Verify that send receives exactly the QueryCommand
             * generated by the function.
             */
            const sentCommand =
                mockSend.firstCall.args[0];

            assert.deepStrictEqual(
                sentCommand.input,
                {
                    TableName: "pn-PortFatDownload",
                    IndexName: "statusMonthSent-index",

                    KeyConditionExpression:
                        "#status = :status AND #monthSent = :monthSent",

                    ExpressionAttributeNames: {
                        "#status": "status",
                        "#monthSent": "monthSent"
                    },

                    ExpressionAttributeValues: {
                        ":status": "COMPLETED",
                        ":monthSent": "2026-10"
                    }
                }
            );

            assert.deepStrictEqual(
                result,
                expectedItems
            );
        });

        it("should pass monthSent exactly as received to the query", async () => {
            mockSend.resolves({
                Items: []
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            await getCompletedRecordsByMonthSent("2030-05");

            sinon.assert.calledOnce(QueryCommand);

            const queryInput =
                QueryCommand.firstCall.args[0];

            assert.deepStrictEqual(
                queryInput.ExpressionAttributeValues,
                {
                    ":status": "COMPLETED",
                    ":monthSent": "2030-05"
                }
            );

            sinon.assert.calledOnce(mockSend);
        });

        it("should always query status COMPLETED", async () => {
            mockSend.resolves({
                Items: []
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            await getCompletedRecordsByMonthSent("2026-10");

            const queryInput =
                QueryCommand.firstCall.args[0];

            assert.strictEqual(
                queryInput
                    .ExpressionAttributeValues[":status"],
                "COMPLETED"
            );
        });

        it("should use statusMonthSent-index", async () => {
            mockSend.resolves({
                Items: []
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            await getCompletedRecordsByMonthSent("2026-10");

            const queryInput =
                QueryCommand.firstCall.args[0];

            assert.strictEqual(
                queryInput.IndexName,
                "statusMonthSent-index"
            );
        });

        it("should use the expected key condition expression", async () => {
            mockSend.resolves({
                Items: []
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            await getCompletedRecordsByMonthSent("2026-10");

            const queryInput =
                QueryCommand.firstCall.args[0];

            assert.strictEqual(
                queryInput.KeyConditionExpression,
                "#status = :status AND #monthSent = :monthSent"
            );
        });

        it("should map reserved attribute names correctly", async () => {
            mockSend.resolves({
                Items: []
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            await getCompletedRecordsByMonthSent("2026-10");

            const queryInput =
                QueryCommand.firstCall.args[0];

            assert.deepStrictEqual(
                queryInput.ExpressionAttributeNames,
                {
                    "#status": "status",
                    "#monthSent": "monthSent"
                }
            );
        });
    });

    describe("table name configuration", () => {
        it("should use default table name when environment variable is not defined", async () => {
            delete process.env.PORTFAT_DOWNLOAD_TABLE_NAME;

            mockSend.resolves({
                Items: []
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            await getCompletedRecordsByMonthSent("2026-10");

            const queryInput =
                QueryCommand.firstCall.args[0];

            assert.strictEqual(
                queryInput.TableName,
                "pn-PortFatDownload"
            );
        });

        it("should use table name from PORTFAT_DOWNLOAD_TABLE_NAME when defined", async () => {
            process.env.PORTFAT_DOWNLOAD_TABLE_NAME =
                "custom-portfat-download-table";

            mockSend.resolves({
                Items: []
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            await getCompletedRecordsByMonthSent("2026-10");

            sinon.assert.calledOnce(QueryCommand);

            const queryInput =
                QueryCommand.firstCall.args[0];

            assert.strictEqual(
                queryInput.TableName,
                "custom-portfat-download-table"
            );

            sinon.assert.calledOnce(mockSend);
        });

        it("should use default table name when environment variable is empty", async () => {
            process.env.PORTFAT_DOWNLOAD_TABLE_NAME = "";

            mockSend.resolves({
                Items: []
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            await getCompletedRecordsByMonthSent("2026-10");

            const queryInput =
                QueryCommand.firstCall.args[0];

            assert.strictEqual(
                queryInput.TableName,
                "pn-PortFatDownload"
            );
        });
    });

    describe("response handling", () => {
        it("should return all Items received from DynamoDB", async () => {
            const items = [
                {
                    id: "1",
                    status: "COMPLETED"
                },
                {
                    id: "2",
                    status: "COMPLETED"
                },
                {
                    id: "3",
                    status: "COMPLETED"
                }
            ];

            mockSend.resolves({
                Items: items
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            const result =
                await getCompletedRecordsByMonthSent("2026-10");

            assert.deepStrictEqual(
                result,
                items
            );

            /*
             * No transformation is performed on Dynamo records.
             */
            assert.strictEqual(
                result,
                items
            );

            sinon.assert.calledOnce(mockSend);
        });

        it("should return an empty array when DynamoDB returns an empty Items array", async () => {
            mockSend.resolves({
                Items: []
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            const result =
                await getCompletedRecordsByMonthSent("2026-10");

            assert.deepStrictEqual(
                result,
                []
            );

            sinon.assert.calledOnce(mockSend);
        });

        it("should return an empty array when Items is undefined", async () => {
            mockSend.resolves({
                Items: undefined
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            const result =
                await getCompletedRecordsByMonthSent("2026-10");

            assert.deepStrictEqual(
                result,
                []
            );

            sinon.assert.calledOnce(mockSend);
        });

        it("should return an empty array when Items property is missing", async () => {
            mockSend.resolves({});

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            const result =
                await getCompletedRecordsByMonthSent("2026-10");

            assert.deepStrictEqual(
                result,
                []
            );

            sinon.assert.calledOnce(mockSend);
        });

        it("should return an empty array when Items is null", async () => {
            mockSend.resolves({
                Items: null
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            const result =
                await getCompletedRecordsByMonthSent("2026-10");

            assert.deepStrictEqual(
                result,
                []
            );

            sinon.assert.calledOnce(mockSend);
        });

        it("should ignore other DynamoDB response properties", async () => {
            const items = [
                {
                    id: "1",
                    status: "COMPLETED"
                }
            ];

            mockSend.resolves({
                Items: items,
                Count: 1,
                ScannedCount: 1,
                ConsumedCapacity: {
                    CapacityUnits: 0.5
                },
                LastEvaluatedKey: {
                    id: "some-id"
                }
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            const result =
                await getCompletedRecordsByMonthSent("2026-10");

            assert.deepStrictEqual(
                result,
                items
            );
        });
    });

    describe("errors", () => {
        it("should propagate an error thrown by docClient.send", async () => {
            const error =
                new Error("DynamoDB query failed");

            mockSend.rejects(error);

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            let caughtError;

            try {
                await getCompletedRecordsByMonthSent("2026-10");
            } catch (err) {
                caughtError = err;
            }

            assert.ok(caughtError);

            assert.strictEqual(
                caughtError.message,
                "DynamoDB query failed"
            );

            sinon.assert.calledOnce(QueryCommand);
            sinon.assert.calledOnce(mockSend);
        });

        it("should propagate the exact error instance returned by DynamoDB", async () => {
            const error =
                new Error(
                    "Provisioned throughput exceeded"
                );

            error.name =
                "ProvisionedThroughputExceededException";

            mockSend.rejects(error);

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            let caughtError;

            try {
                await getCompletedRecordsByMonthSent("2026-10");
            } catch (err) {
                caughtError = err;
            }

            assert.strictEqual(
                caughtError,
                error
            );

            sinon.assert.calledOnce(mockSend);
        });

        it("should propagate ResourceNotFoundException", async () => {
            const error =
                new Error(
                    "Requested resource not found"
                );

            error.name =
                "ResourceNotFoundException";

            mockSend.rejects(error);

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            let caughtError;

            try {
                await getCompletedRecordsByMonthSent("2026-10");
            } catch (err) {
                caughtError = err;
            }

            assert.ok(caughtError);

            assert.strictEqual(
                caughtError.name,
                "ResourceNotFoundException"
            );

            assert.strictEqual(
                caughtError.message,
                "Requested resource not found"
            );

            sinon.assert.calledOnce(mockSend);
        });

        it("should propagate AccessDeniedException", async () => {
            const error =
                new Error("Access denied");

            error.name =
                "AccessDeniedException";

            mockSend.rejects(error);

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            let caughtError;

            try {
                await getCompletedRecordsByMonthSent("2026-10");
            } catch (err) {
                caughtError = err;
            }

            assert.strictEqual(
                caughtError,
                error
            );

            sinon.assert.calledOnce(mockSend);
        });

        it("should not retry send when DynamoDB returns an error", async () => {
            const error =
                new Error("DynamoDB error");

            mockSend.rejects(error);

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            let caughtError;

            try {
                await getCompletedRecordsByMonthSent("2026-10");
            } catch (err) {
                caughtError = err;
            }

            assert.strictEqual(
                caughtError,
                error
            );

            /*
             * This module contains no application-level retry logic.
             * AWS SDK retries, if configured, happen internally.
             */
            sinon.assert.calledOnce(mockSend);
        });
    });

    describe("edge cases for monthSent", () => {
        it("should pass undefined monthSent to QueryCommand without modifying it", async () => {
            mockSend.resolves({
                Items: []
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            await getCompletedRecordsByMonthSent(undefined);

            const queryInput =
                QueryCommand.firstCall.args[0];

            assert.deepStrictEqual(
                queryInput.ExpressionAttributeValues,
                {
                    ":status": "COMPLETED",
                    ":monthSent": undefined
                }
            );

            sinon.assert.calledOnce(mockSend);
        });

        it("should pass null monthSent to QueryCommand without modifying it", async () => {
            mockSend.resolves({
                Items: []
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            await getCompletedRecordsByMonthSent(null);

            const queryInput =
                QueryCommand.firstCall.args[0];

            assert.deepStrictEqual(
                queryInput.ExpressionAttributeValues,
                {
                    ":status": "COMPLETED",
                    ":monthSent": null
                }
            );

            sinon.assert.calledOnce(mockSend);
        });

        it("should pass empty monthSent to QueryCommand without modifying it", async () => {
            mockSend.resolves({
                Items: []
            });

            const {
                getCompletedRecordsByMonthSent
            } = loadModule();

            await getCompletedRecordsByMonthSent("");

            const queryInput =
                QueryCommand.firstCall.args[0];

            assert.deepStrictEqual(
                queryInput.ExpressionAttributeValues,
                {
                    ":status": "COMPLETED",
                    ":monthSent": ""
                }
            );

            sinon.assert.calledOnce(mockSend);
        });
    });
});